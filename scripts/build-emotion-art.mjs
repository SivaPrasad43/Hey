// Run: npm run emotion-art
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/fluent-emoji-flat/icons.json');

const pick = {
  faces: {
    calm: 'relieved-face',
    happy: 'beaming-face-with-smiling-eyes',
    angry: 'pouting-face',
    sad: 'pleading-face',
    lovely: 'smiling-face-with-heart-eyes',
  },
  particles: {
    calm: 'herb',
    happy: 'sparkles',
    angry: 'anger-symbol',
    sad: 'droplet',
    lovely: 'red-heart',
  },
};

const body = (name) => {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Missing Fluent Emoji icon: ${name}`);
  return icon.body;
};

const block = (kind) =>
  Object.entries(pick[kind])
    .map(([mood, name]) => `  // ${name}\n  ${mood}: ${JSON.stringify(body(name))},`)
    .join('\n');

const out = `/* eslint-disable */
// GENERATED by scripts/build-emotion-art.mjs. Do not edit by hand.
// Artwork: Fluent Emoji (flat) by Microsoft Corporation, MIT License,
// https://github.com/microsoft/fluentui-emoji/blob/main/LICENSE
import type { MoodId } from './moods';

/** 32×32 SVG bodies for each feeling's face. */
export const EMOTION_FACES: Record<MoodId, string> = {
${block('faces')}
};

/** 32×32 SVG bodies for each feeling's burst particle. */
export const EMOTION_PARTICLES: Record<MoodId, string> = {
${block('particles')}
};
`;
writeFileSync(new URL('../src/app/core/emotion-art.ts', import.meta.url), out);
console.log('wrote src/app/core/emotion-art.ts');
